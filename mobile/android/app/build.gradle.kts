    // (.github/workflows/android-release.yml); without it a local release build uses the debug key.
    val keystore = System.getenv("MONETRA_KEYSTORE_PATH")
    signingConfigs {
        if (keystore != null) {
            create("release") {
                storeFile = file(keystore)
                storePassword = System.getenv("MONETRA_KEYSTORE_PASSWORD")
                keyAlias = System.getenv("MONETRA_KEY_ALIAS")
                keyPassword = System.getenv("MONETRA_KEY_PASSWORD")
            }
        }
    }

    buildTypes {
        release {
            signingConfig = signingConfigs.findByName("release") ?: signingConfigs.getByName("debug")
        }
    }
